// Whole-page templates. Structurally these are ComponentEntry like everything
// else in the registry — same catalog, same AI prompt — and the only thing
// separating them is `kind: "template"`.
//
// A template ships its entire directory: page.tsx is variants[0], every other
// file is a `peer`. Same mapped-array shape FILE_EXPLORER_PEERS uses in
// power-user-systems.ts, for the same reason — the array IS the transitive
// closure, and `check:registry` is what proves it.

/** The shared `cn` helper, same peer the component entries already ship. */
